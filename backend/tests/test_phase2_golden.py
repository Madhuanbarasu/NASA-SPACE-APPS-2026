"""Phase 2 golden test: horizon and analysis outputs are unchanged by the uncertainty work.

The golden files in tests/golden/ were recorded once from unmodified origin/main (commit 7ebe3a4,
ALGORITHM_VERSION 1.2.0) on the synthetic crater, before any Phase 2 engine edit, and must never be
regenerated from edited engine code. Phase 2 changes only horizon *uncertainty* (sigma), the flags
derived from it and provenance; horizon elevations, blocking distances, incompleteness, disk
visibility, power and event times must be identical.

Tolerances only absorb last-bit floating-point differences between machines (transcendental
functions may round differently on other CPUs): horizon elevations 1e-7 deg (the V-06 threshold is
1e-2 deg), event times 1 s (the detector's bisection tolerance), display values one rounding unit.
The `sha256` recorded for each terrain level is the digest of a fixture GeoTIFF regenerated by the
local GDAL build, so it is checked against the file the run actually used rather than the recording
machine's file (see _check_levels); every other recorded field is compared as is.
"""
from __future__ import annotations

import json
import math
from pathlib import Path

import numpy as np
import pytest

from conftest import needs_kernels

GOLDEN = Path(__file__).resolve().parent / "golden"
SNAP = json.loads((GOLDEN / "phase2_analysis.json").read_text())
ARR = np.load(GOLDEN / "phase2_horizons.npz")


def _close(a, b, path=""):
    """Recursive comparison of golden JSON b with new JSON a; only keys present in the golden are checked."""
    if isinstance(b, dict):
        assert isinstance(a, dict), path
        for k, v in b.items():
            assert k in a, f"{path}.{k} missing"
            _close(a[k], v, f"{path}.{k}")
    elif isinstance(b, list):
        assert isinstance(a, list) and len(a) == len(b), f"{path}: length {len(a)} != {len(b)}"
        for i, (x, y) in enumerate(zip(a, b)):
            _close(x, y, f"{path}[{i}]")
    elif isinstance(b, bool) or b is None or isinstance(b, str):
        assert a == b, f"{path}: {a!r} != {b!r}"
    elif isinstance(b, (int, float)):
        assert isinstance(a, (int, float)) and not isinstance(a, bool), path
        if math.isnan(b):
            assert math.isnan(a), path
        else:
            assert abs(a - b) <= max(1e-4, 1e-6 * abs(b)), f"{path}: {a} != {b}"
    else:  # pragma: no cover
        raise AssertionError(f"{path}: unexpected type {type(b)}")


def _check_levels(got: list, golden: list) -> None:
    """Terrain products used by the horizon: every recorded field must match, except `sha256`.

    `sha256` is the digest of the synthetic fixture GeoTIFF that conftest regenerates in each session with
    GDAL's deflate compression. Its bytes depend on the local GDAL / zlib / libdeflate build (for example,
    the rasterio wheels for Windows and Linux), while its decoded heights do not, so the golden value
    recorded on Linux cannot match a Windows run. It is a provenance pointer, not a horizon output. The
    scientific content is covered by the elevation, incompleteness and blocking-distance comparisons
    (1e-7 deg), which `_close` checks before the levels. Instead of comparing it with another machine's
    file, the provenance digest must equal the SHA-256 of the file this run actually used.
    """
    from lunaops.engine.dem import product_key, read_registry, resolve_dem_path
    from lunaops.engine.kernels import sha256_of

    assert len(got) == len(golden)
    reg = {product_key(p): p for p in read_registry()["products"]}
    for g, want in zip(got, golden):
        _close(g, {k: v for k, v in want.items() if k != "sha256"}, f"horizon.levels[{g.get('key')}]")
        rec = reg[g["key"]]
        assert g["sha256"] == rec["sha256"] == sha256_of(resolve_dem_path(rec["path"])), g["key"]


def test_level_digest_tracks_encoding_not_terrain(tmp_path):
    """Why `sha256` is excluded from the cross-machine comparison: the same heights written with different
    deflate settings (as different GDAL builds do) give different file digests but identical pixels."""
    import hashlib

    import rasterio
    from rasterio.crs import CRS
    from rasterio.transform import from_origin

    from lunaops.engine.kernels import sha256_of
    from lunaops.testing import STEREO_PROJ4, synthetic_height

    n, px = 200, 20.0
    xs = -2000.0 + px * (np.arange(n) + 0.5)
    Z = synthetic_height(*np.meshgrid(xs, -xs), "crater").astype(np.float32)
    digests, pixels = set(), set()
    for i, opts in enumerate(({"compress": "deflate"}, {"compress": "deflate", "zlevel": 9},
                              {"compress": "deflate", "predictor": 3})):
        p = tmp_path / f"f{i}.tif"
        with rasterio.open(p, "w", driver="GTiff", width=n, height=n, count=1, dtype="float32",
                           crs=CRS.from_proj4(STEREO_PROJ4), transform=from_origin(-2000.0, 2000.0, px, px),
                           nodata=-9999.0, tiled=True, **opts) as dst:
            dst.write(Z, 1)
        with rasterio.open(p) as src:
            pixels.add(hashlib.sha256(src.read(1).tobytes()).hexdigest())
        digests.add(sha256_of(p))
    assert len(pixels) == 1 and len(digests) == 3


@needs_kernels
@pytest.mark.parametrize("i", range(len(SNAP["sites"])))
@pytest.mark.parametrize("h", SNAP["heights"])
def test_horizon_values_unchanged(kernels, synthetic_crater, i, h):
    from lunaops.engine.horizon import compute_horizon

    lat, lon = SNAP["sites"][i]
    hz = compute_horizon(lat, lon, h)
    tag = f"s{i}_h{int(h)}"
    np.testing.assert_allclose(hz.h_deg, ARR[f"{tag}_h_deg"], rtol=0, atol=1e-7)
    np.testing.assert_array_equal(hz.incomplete, ARR[f"{tag}_incomplete"])
    np.testing.assert_allclose(hz.block_dist_m, ARR[f"{tag}_block_dist_m"], rtol=0, atol=1e-6)
    assert abs(hz.ground_h_m - float(ARR[f"{tag}_ground_h_m"][0])) <= 1e-9


@needs_kernels
def _earth_edge_shift_bound_s(res, ev) -> float:
    """Largest possible shift (s) of an Earth upper/lower-limb event between the pre-Phase-3 circular disk
    (equatorial radius) and the Phase 3 oblate limb: the edge clearance moves by at most
    (alpha_old - beta)(1 + S/c_min) (every limb point lies between radii beta and alpha_old), divided by
    the clearance rate at the event (central difference of the Phase 3 clearance), plus the 1 s
    bisection tolerance of either run."""
    from lunaops.engine.analysis import AnalysisRequest, get_horizon
    from lunaops.engine.earth import intrinsic_radii
    from lunaops.engine.ephem import Site
    from lunaops.engine.events import EventConfig, EventDetector
    from lunaops.engine.visibility import HorizonProfile

    req = SNAP["request"]
    hz = get_horizon(req["lat"], req["lon"], 0.0)
    det = EventDetector(Site(req["lat"], req["lon"], hz.ground_h_m, 0.0),
                        HorizonProfile(hz.h_deg, hz.incomplete, hz.sigma_deg, flags=hz.flag_arrays()), EventConfig())
    fn = ev["function"]
    a, b = det.evaluate(ev["et"] - 30.0), det.evaluate(ev["et"] + 30.0)
    rate = abs(b.vals[fn] - a.vals[fn]) / 60.0
    g = det.evaluate(ev["et"]).geo["earth"]
    d = _earth_dist(det, ev["et"])
    alpha_old = math.degrees(math.asin(6378.137 / d))
    _, beta = intrinsic_radii(d)
    dg = (alpha_old - math.degrees(beta)) * (1.0 + g["S"] / g["c_min"])
    return dg / max(rate, 1e-12) + 2.0


def _earth_dist(det, et) -> float:
    from lunaops.engine.ephem import sample_target
    return float(sample_target(det.site, "earth", [et]).dist_km[0])


@needs_kernels
def test_analysis_outputs_unchanged_except_flags(kernels, synthetic_crater):
    """Phase 2 golden, with Phase 3's oblate Earth: horizon, Sun, Earth position and Earth centre values stay
    identical; Earth radius, Earth visible fraction and Earth limb events may change only within bounds
    derived from the model (limb radii between beta and the old alpha)."""
    from lunaops.engine.analysis import AnalysisRequest, analyze
    from lunaops.engine.earth import intrinsic_radii, pole_area_bound

    res = analyze(AnalysisRequest(**SNAP["request"]))
    assert len(SNAP["events"]) >= 10, "golden window must contain events"
    # horizon JSON fields that existed before Phase 2 (Phase 2 may only add keys)
    golden_h = dict(SNAP["horizon"])
    golden_levels = golden_h.pop("levels")
    _close(res["horizon"], golden_h, "horizon")
    _check_levels(res["horizon"]["levels"], golden_levels)
    # series: everything identical except Earth's radius and visible fraction (Phase 3), checked below
    gs = json.loads(json.dumps(SNAP["series"]))
    old_rho = gs["earth"].pop("rho")
    old_f = gs["earth"].pop("f")
    _close(res["series"], gs, "series")
    new_rho, new_f = res["series"]["earth"]["rho"], res["series"]["earth"]["f"]
    alpha_new, beta = intrinsic_radii(np.asarray(res["series"]["earth"]["dist_km"], dtype=float))
    for i, (ro, rn, fo, fn) in enumerate(zip(old_rho, new_rho, old_f, new_f)):
        lo = math.degrees(beta[i]) - ro - 1e-5                  # display rounding
        hi = math.degrees(alpha_new[i]) - ro + 1e-5
        assert lo <= rn - ro <= hi, ("earth.rho", i, ro, rn)
        if fo is None or fn is None:
            assert fo is None and fn is None, ("earth.f unknown", i)
            continue
        alpha_old = math.radians(ro)
        bound = pole_area_bound(alpha_old, float(beta[i]), alpha_old - float(beta[i]))
        assert abs(fn - fo) <= bound + 1e-5, ("earth.f", i, fo, fn, bound)
    # events: same sequence; Sun and Earth-centre events within the 1 s bisection tolerance; Earth limb events
    # within the model-derived shift bound
    assert [(e["function"], e["direction"], e["name"], e["target"]) for e in res["events"]] == \
        [(e["function"], e["direction"], e["name"], e["target"]) for e in SNAP["events"]]
    limb_shift = 2.0
    for a, b in zip(res["events"], SNAP["events"]):
        if a["function"] in ("earth_top", "earth_bot"):
            bnd = _earth_edge_shift_bound_s(res, a)
            limb_shift = max(limb_shift, bnd)
            assert abs(a["et"] - b["et"]) <= bnd, (a, b, bnd)
        else:
            assert abs(a["et"] - b["et"]) <= 1.0, (a, b)
    # intervals: same states; edges within 1 s, Earth limb-rule edges within the limb-event bound
    assert set(res["intervals"]) == set(SNAP["intervals"])
    for k, ivs in SNAP["intervals"].items():
        got = res["intervals"][k]
        tol = limb_shift if k in ("earth_any", "earth_full") else 1.0
        assert [iv["state"] for iv in got] == [iv["state"] for iv in ivs], k
        for a, b in zip(got, ivs):
            assert abs(a["start_et"] - b["start_et"]) <= tol and abs(a["end_et"] - b["end_et"]) <= tol, (k, a, b)
            if k not in ("earth_any", "earth_full"):
                assert a["brief"] == b["brief"]
    # summaries: every pre-Phase-2 value except flag counts; Earth limb-rule durations within the edge bound
    for k, v in SNAP["summary"].items():
        if isinstance(v, dict) and "windows" in v:
            n_edges = 2 * max(1, len(SNAP["intervals"].get(k, [])))
            for f, x in v.items():
                got = res["summary"][k][f]
                if k in ("earth_any", "earth_full") and f in ("hours", "longest_gap_h", "longest_window_h"):
                    assert abs(got - x) <= n_edges * limb_shift / 3600.0 + 1e-3, (k, f, got, x)
                elif k in ("earth_any", "earth_full") and f == "percent":
                    span_h = (res["window"]["end_et"] - res["window"]["start_et"]) / 3600.0
                    assert abs(got - x) <= 100.0 * (n_edges * limb_shift / 3600.0) / span_h + 1e-3, (k, f, got, x)
                else:
                    assert abs(got - x) <= max(1e-3, 1e-6 * abs(x)), (k, f, got, x)
        else:
            _close(res["summary"][k], v, f"summary.{k}")
