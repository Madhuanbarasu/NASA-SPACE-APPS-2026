#!/usr/bin/env node
// Phase 5 final (IB-5 findings 1 and 2): third-party notices for the browser build, assembled only from the licence
// files the installed packages ship (no licence text is written by hand or inferred).
//
//   node scripts/gen-notices.mjs <vite_modules.json>
//
// <vite_modules.json> is the output of docs/validation_evidence/ib5_2026-11-11/scripts/vite_modules.mjs: the packages
// whose code the production Vite/Rollup build actually renders into the bundle. The Archivo font package is added when
// its WOFF2 files are in frontend/dist/assets. Writes public/THIRD_PARTY_NOTICES.txt and public/OFL.txt (copied into
// dist by the next build). If any shipped package has no licence file, nothing is written and the exit code is 1.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const FE = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const modulesFile = process.argv[2];
if (!modulesFile) { console.error("usage: node scripts/gen-notices.mjs <vite_modules.json>"); process.exit(2); }
const mods = JSON.parse(fs.readFileSync(modulesFile, "utf8"));
const FONT = "@fontsource-variable/archivo";
const shipped = mods.shipped_with_rendered_code.filter((p) => p !== "(project source)");
if (fs.readdirSync(path.join(FE, "dist", "assets")).some((f) => /^archivo-.*\.woff2$/.test(f)) && !shipped.includes(FONT)) shipped.push(FONT);
shipped.sort();

const LICENCE_FILE = /^(licen[cs]e|copying|notice)(\.(md|txt))?$/i;
const blocks = [], missing = [], summary = [];
for (const name of shipped) {
  const dir = path.join(FE, "node_modules", ...name.split("/"));
  const pkg = JSON.parse(fs.readFileSync(path.join(dir, "package.json"), "utf8"));
  const files = fs.readdirSync(dir).filter((f) => LICENCE_FILE.test(f)).sort();
  if (!files.length) { missing.push(`${name}@${pkg.version}`); continue; }
  const declared = typeof pkg.license === "string" ? pkg.license : pkg.license?.type ?? "not declared";
  summary.push({ name, version: pkg.version, declared, files });
  for (const f of files) {
    const text = fs.readFileSync(path.join(dir, f), "utf8").replace(/\r\n/g, "\n").trimEnd();
    blocks.push(`${"=".repeat(78)}\n${name}@${pkg.version}  (declared licence: ${declared}; file: ${f})\n${"=".repeat(78)}\n\n${text}\n`);
  }
}
if (missing.length) { console.error("no licence file for: " + missing.join(", ") + "; nothing written"); process.exit(1); }

const header = `LUNA-OPS browser build: third-party notices

This file lists every third-party package whose code or font files are shipped in this browser build (frontend/dist),
with the full text of the licence file that package ships. It was generated by frontend/scripts/gen-notices.mjs from the
installed packages' own licence files; the package list comes from the production Vite/Rollup build. The OFL text for
the Archivo font is also provided separately as OFL.txt. The Moon imagery under moon/ is described in
moon/ATTRIBUTION.txt.

Packages (${summary.length}):
${summary.map((s) => `  ${s.name}@${s.version}  ${s.declared}`).join("\n")}

`;
fs.writeFileSync(path.join(FE, "public", "THIRD_PARTY_NOTICES.txt"), header + blocks.join("\n"), "utf8");
const font = summary.find((s) => s.name === FONT);
if (font) {
  const dir = path.join(FE, "node_modules", ...FONT.split("/"));
  fs.writeFileSync(path.join(FE, "public", "OFL.txt"), fs.readFileSync(path.join(dir, font.files[0]), "utf8").replace(/\r\n/g, "\n"), "utf8");
}
console.log(`notices: ${summary.length} packages, ${blocks.length} licence files; OFL.txt ${font ? "written" : "not needed"}`);
