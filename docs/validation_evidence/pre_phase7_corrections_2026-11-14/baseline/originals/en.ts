// English interface strings for LUNA-OPS (blueprint C10: English, text kept separate from code).
//
// Every user-facing string in the interface lives here: headings, labels, buttons, placeholders, errors,
// empty states, tooltips, accessible names, chart/map/3D text and the Technical/Public mode text.
// Components read it through `S` from "../i18n" (never by copying text), so a missing or misspelt key is a
// TypeScript error and `npm run check:strings` (frontend/scripts/check-strings.mjs) reports unknown keys,
// unused keys and hardcoded text in components.
//
// Conventions:
// - plain text is a string;
// - text with values is a typed function returning a string;
// - text with markup inside (bold numbers, code) is a template with {name} placeholders rendered by
//   `rich()` (src/i18n/rich.ts), whose placeholder names are checked at compile time;
// - this file has no imports and no logic beyond string assembly, so it can be loaded by the checker.
//
// Strings that come from the API (job messages, warnings, kernel errors, event names, label kinds, test
// statuses and details, catalogue names) are data, not interface text, and are shown as received.

